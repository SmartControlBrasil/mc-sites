export function getServiceBySlug(slug: string | undefined): ServiceItem | undefined {
  if (!slug) {
    return undefined;
  }

  return MCSITES_SERVICES.find((service) => service.slug === slug);
}

export function getServiceDetailPath(slug: string): string {
  return `/service-details/${slug}`;
}

export function getAdjacentServices(slug: string): {
  previous?: ServiceItem;
  next?: ServiceItem;
} {
  const index = MCSITES_SERVICES.findIndex((service) => service.slug === slug);

  if (index === -1) {
    return {};
  }

  return {
    previous: index > 0 ? MCSITES_SERVICES[index - 1] : undefined,
    next: index < MCSITES_SERVICES.length - 1 ? MCSITES_SERVICES[index + 1] : undefined,
  };
}
